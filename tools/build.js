#!/usr/bin/env node
/* Builds the hosted PWA from the single source of truth, src/Ledger.html (the same file that runs inside Apps Script):
 *   src/Ledger.html  ->  index.html (head gets manifest/icons/css link)  +  css/styles.css
 * and stamps a content hash into sw.js so every change ships a new service worker.
 * Usage:  node tools/build.js            write the files
 *         node tools/build.js --check    exit 1 if the files on disk are out of date (used by the tests) */
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8');

function build() {
  const src = read('src/Ledger.html');
  const m = /<style>([\s\S]*?)<\/style>/.exec(src);
  if (!m) throw new Error('no <style> block in src/Ledger.html');
  const css = '/* GENERATED by tools/build.js from src/Ledger.html — edit the source, not this file. */\n' + m[1].replace(/^\n/, '').replace(/\s+$/, '') + '\n';
  const head = [
    '<link rel="manifest" href="manifest.json">',
    '<link rel="icon" href="icons/favicon.svg" type="image/svg+xml">',
    '<link rel="icon" href="icons/icon-192.png" sizes="192x192" type="image/png">',
    '<link rel="apple-touch-icon" href="icons/apple-touch-icon.png">',
    '<link rel="stylesheet" href="css/styles.css">'
  ].join('\n');
  let html = src.replace(m[0], head);
  html = html.replace('<!DOCTYPE html>', '<!DOCTYPE html>\n<!-- GENERATED by tools/build.js from src/Ledger.html — edit the source, not this file. -->');
  html = html.replace('<body>', '<body>\n<noscript><p style="padding:24px;font-family:sans-serif">Ye app chalane ke liye JavaScript on karo.</p></noscript>');
  const assets = ['manifest.json', ...fs.readdirSync(path.join(root, 'icons')).sort().map(f => 'icons/' + f)];
  const h = crypto.createHash('sha256').update(html).update(css);
  assets.forEach(a => h.update(fs.readFileSync(path.join(root, a))));
  const stamp = h.digest('hex').slice(0, 12);
  const sw = read('sw.js').replace(/const BUILD = '[^']*';/, "const BUILD = '" + stamp + "';");
  return { 'index.html': html, 'css/styles.css': css, 'sw.js': sw, stamp };
}

if (require.main === module) {
  const out = build();
  if (process.argv.includes('--check')) {
    const stale = ['index.html', 'css/styles.css', 'sw.js'].filter(f => !fs.existsSync(path.join(root, f)) || read(f) !== out[f]);
    if (stale.length) { console.error('OUT OF DATE (run: node tools/build.js): ' + stale.join(', ')); process.exit(1); }
    console.log('up to date, build ' + out.stamp);
  } else {
    ['index.html', 'css/styles.css', 'sw.js'].forEach(f => { fs.mkdirSync(path.dirname(path.join(root, f)), { recursive: true }); fs.writeFileSync(path.join(root, f), out[f]); });
    console.log('built index.html, css/styles.css, sw.js  (build ' + out.stamp + ')');
  }
}
module.exports = { build };
